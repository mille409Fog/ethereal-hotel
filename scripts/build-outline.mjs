/**
 * Builds `/wanderquest`'s map outlines from public-domain boundary files.
 *
 *     npm run outline:build
 *
 * Like `fetch-gallery.mjs`, this writes a build *input*: the output is a
 * committed TypeScript module of SVG path data, so the build fetches nothing,
 * a visitor's browser contacts no map host, and the bundle carries no
 * projection library. It needs the network and runs by hand; CI never runs
 * it, and `wanderquest.spec.ts` checks what it committed.
 *
 * An outline is deliberately the roughest thing that still reads as the
 * place. The source is the coarsest scale the Census publishes, and it is
 * roughened further on the way: simplified to `TOLERANCE` in the 960 × 600
 * frame, rounded to whole units, and stripped of every island smaller than
 * `MIN_AREA`. The spec holds the result under a size ceiling, so a tolerance
 * nudged down for looks has to raise that number in plain sight.
 *
 * The state list is read from `src/app/wanderquest/places.data.ts` (Node
 * strips the types), so there is no second list to drift. A state the file
 * does not carry stops the script; a feature that is not a state — DC and
 * Puerto Rico, which the file includes — is left out and named on the way.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

import { STATES } from '../src/app/wanderquest/places.data.ts';
import {
  albersUsa,
  pathData,
  readPolygons,
  readTable,
  unzip,
  USA_FRAME,
  viewBoxOf,
} from './outline.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** The newest vintage, at 1:20,000,000, the coarsest of the three scales. */
const VINTAGE = 2025;
const NAME = `cb_${VINTAGE}_us_state_20m`;
const SOURCE = `https://www2.census.gov/geo/tiger/GENZ${VINTAGE}/shp/${NAME}.zip`;

/** How far, in frame units, a simplified edge may stray from the source. */
const TOLERANCE = 1.5;

/** Rings smaller than this many square frame units are not drawn. */
const MIN_AREA = 12;

/** Room left around the drawn shapes, so a border stroke is not clipped. */
const MARGIN = 2;

const OUTPUT = path.join(repoRoot, 'src', 'app', 'wanderquest', 'states.outline.ts');

async function fetchFiles() {
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`the Census answered ${response.status} for ${SOURCE}`);
  const files = unzip(Buffer.from(await response.arrayBuffer()));
  const file = (extension) => {
    const found = files.get(`${NAME}.${extension}`);
    if (!found) throw new Error(`${NAME}.zip has no .${extension}`);
    return found;
  };
  return { shp: file('shp'), dbf: file('dbf') };
}

async function main() {
  const { shp, dbf } = await fetchFiles();
  const polygons = readPolygons(shp);
  const rows = readTable(dbf);
  const wanted = new Set(STATES.map((state) => state.id));
  const projectionFor = albersUsa();

  const shapes = new Map();
  const skipped = [];
  rows.forEach((row, i) => {
    const id = row.STUSPS;
    if (!wanted.has(id)) {
      skipped.push(`${id} (${row.NAME})`);
      return;
    }
    shapes.set(
      id,
      pathData(polygons[i], projectionFor(id), { tolerance: TOLERANCE, minArea: MIN_AREA })
    );
  });

  const missing = STATES.filter((state) => !shapes.get(state.id));
  if (missing.length > 0) {
    throw new Error(`${NAME} has no drawable shape for ${missing.map((s) => s.id).join(', ')}`);
  }

  const fetched = new Date().toISOString().slice(0, 10);
  const entries = STATES.map((state) => `  { id: '${state.id}', d: '${shapes.get(state.id)}' },`);
  const source = `/**
 * The fifty states, outlined. GENERATED by \`npm run outline:build\`
 * (\`scripts/build-outline.mjs\`) — edit the script, not this file.
 *
 * Source: US Census Bureau, ${VINTAGE} cartographic boundary file, states,
 * 1:20,000,000 (\`${NAME}\`), a work of the US government and so in the
 * public domain. ${SOURCE}
 * Fetched ${fetched}.
 *
 * Projected as d3's \`geoAlbersUsa\` into a ${USA_FRAME.width} × ${USA_FRAME.height} frame, Alaska and
 * Hawaii inset, then cropped to the shapes; simplified to ${TOLERANCE} units, rounded to
 * whole units, islands under ${MIN_AREA} square units dropped. Left out because they are
 * not states: ${skipped.join(', ')}.
 */
import type { StateId } from './places.data';
import type { IOutline } from './outline';

export const STATES_OUTLINE: IOutline<StateId> = {
  label: 'Outline map of the fifty states',
  viewBox: '${viewBoxOf([...shapes.values()], MARGIN)}',
  shapes: [
${entries.join('\n')}
  ],
};
`;

  const options = (await prettier.resolveConfig(OUTPUT)) ?? {};
  await writeFile(OUTPUT, await prettier.format(source, { ...options, filepath: OUTPUT }));

  const bytes = [...shapes.values()].reduce((sum, d) => sum + d.length, 0);
  console.log(
    `Wrote ${path.relative(repoRoot, OUTPUT)}: ${shapes.size} states, ${bytes} bytes of path data.`
  );
  console.log(`Left out: ${skipped.join(', ')}.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
