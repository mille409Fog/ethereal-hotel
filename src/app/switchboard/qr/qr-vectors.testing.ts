/**
 * Reference matrices for `qr.spec.ts`, produced by an encoder that is not
 * ours: the Python `qrcode` package, 8.2, with level M, byte mode, no border
 * and the mask fixed, so the comparison covers placement and masking bit for
 * bit. `#` is dark. Row 0 is the top.
 *
 * One per version, one at full capacity (version 2), the real URL in version
 * 4's two interleaved blocks, and one input that is not ASCII, so the bytes
 * are UTF-8 and not code points.
 *
 * Why `qrcode` and not `segno`, which was tried first: segno 1.6.6's
 * `write_padding_bits` appends `8 - length % 8` zero bits even when the stream
 * already ends on a byte boundary, which in byte mode it always does. So every
 * byte-mode symbol it makes short of capacity carries a `0x00` codeword where
 * ISO/IEC 18004 §7.4.10 puts `0xEC`. It still scans, because a reader stops at
 * the terminator, but it is not the standard, and its matrices agreed with
 * ours only on the inputs that fill their version.
 *
 * Every matrix here, and ours for each input under all eight masks, also
 * decoded with OpenCV 5.1. Excluded from coverage by `coverageExclude`.
 */

